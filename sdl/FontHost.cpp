bool sdl_glyph(i32 height,i32 weight,u16 code,JapaneseFont::Glyph& glyph,std::vector<u8>& pixels){
    if(!started){if(TTF_Init()!=0)return false;started=true;}
    auto& face=faces[{height,weight}];if(!face){face=open_font(height);if(!face)return false;
        TTF_SetFontKerning(face,0);TTF_SetFontHinting(face,TTF_HINTING_NORMAL);if(weight>=600)TTF_SetFontStyle(face,TTF_STYLE_BOLD);}
    int left,right,bottom,top,advance;
    if(TTF_GlyphMetrics32(face,code,&left,&right,&bottom,&top,&advance)!=0)return false;
    auto* image=TTF_RenderGlyph32_Blended(face,code,{255,255,255,255});if(!image)return false;
    auto* rgba=SDL_ConvertSurfaceFormat(image,SDL_PIXELFORMAT_RGBA32,0);SDL_FreeSurface(image);if(!rgba)return false;
    // SDL glyph surfaces already include the font's baseline placement. Switch
    // port: fonts other than MS Gothic (the system-font fallback) have taller
    // line metrics; drop the rows above MS Gothic's ascent (220/256 em) and keep
    // one em, MS Gothic's cell height.
    const i32 skip=std::clamp(TTF_FontAscent(face)-i32(std::lround(height*220.0/256.0)),0,rgba->h);const i32 rows=std::min(rgba->h-skip,height);
    glyph={code,0,i16(advance),0,0,u16(rgba->w),u16(rows)};pixels.resize(size_t(rgba->w)*rows);
    const auto* data=static_cast<const u8*>(rgba->pixels)+skip*rgba->pitch;for(int y=0;y<rows;y++)for(int x=0;x<rgba->w;x++)pixels[y*rgba->w+x]=(u32(data[y*rgba->pitch+x*4+3])*15+127)/255;
    SDL_FreeSurface(rgba);return true;
}
