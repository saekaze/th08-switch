bool BrowserRuntime::native_fonts(){
    const auto dir=host::paths().data_file("fonts");std::vector<u8> bytes;
    if(!sdl_read_file((dir+"/cp932.bin").c_str(),bytes)||bytes.size()!=131072){bytes.resize(131072);std::memcpy(bytes.data(),cp932_map,131072);}
    if(!put_font(0,bytes.data(),u32(bytes.size())))return false;
    if(!sdl_read_file((dir+"/blend.bin").c_str(),bytes)||bytes.size()!=131072){
        // [coverage 0..15][destination 5-bit channel][text 8-bit channel] ->
        // 5-bit result: coverage-weighted mix of the ARGB1555 target and text.
        bytes.resize(131072);
        for(u32 a=0;a<16;++a)for(u32 before=0;before<32;++before)for(u32 text=0;text<256;++text)
            bytes[a*8192+before*256+text]=u8(std::lround(before*(15.0-a)/15.0+text*31.0/255.0*a/15.0));
    }
    if(!put_font(1,bytes.data(),u32(bytes.size())))return false;
    if(!started){if(TTF_Init()!=0)return false;started=true;}
    if(auto* probe=open_font(16)){TTF_CloseFont(probe);return true;}
    host::log("No Japanese font: copy msgothic.ttc (from Windows) next to th08.dat");return false;}
u32 BrowserRuntime::native_font_steps(){
    if(warm_glyphs.empty()){std::set<u16> codes;for(u16 code=32;code<127;code++)codes.insert(code);
        const auto text=read("musiccmt.txt");const auto* p=text.data();const auto* end=p+text.size();while(p<end){const auto code=fonts.encoding.next(p,end);if(code>=32)codes.insert(code);}
        warm_glyphs.assign(codes.begin(),codes.end());}
    return (warm_glyphs.size()*4+15)/16;
}
bool BrowserRuntime::native_font_step(u32 step){
    const i32 profiles[][2]={{16,400},{16,600},{26,600},{28,600}};
    for(u32 i=step*16;i<std::min<u32>((step+1)*16,warm_glyphs.size()*4);i++){
        const auto* profile=profiles[i/warm_glyphs.size()];const auto* font=fonts.find(profile[0],profile[1]);if(!font)return false;
        if(!font->find(warm_glyphs[i%warm_glyphs.size()])&&!font->find(0x30fb))return false;
    }return true;
}
